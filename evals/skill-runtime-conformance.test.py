#!/usr/bin/env python3
import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "skills/skill-runtime-conformance/scripts/audit.py"


class AuditTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        source = self.root / ".claude/skills/demo-skill"
        source.mkdir(parents=True)
        (source / "SKILL.md").write_text("---\nname: demo-skill\ndescription: Demo skill.\n---\n\n# Demo\n", encoding="utf-8")
        self.config = {"version": 1, "canonical": ".claude/skills", "published": ["demo-skill"], "targets": {"codex": {"path": ".agents/skills", "format": "directory"}, "opencode": {"path": ".opencode/skills", "format": "directory"}, "cursor": {"path": ".cursor/rules", "format": "cursor-rule"}}}
        (self.root / ".skill-runtimes.json").write_text(json.dumps(self.config), encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def run_audit(self):
        return subprocess.run(["python3", str(AUDIT), "check", "--root", str(self.root), "--json"], text=True, capture_output=True)

    def publish(self):
        source = self.root / ".claude/skills/demo-skill"
        for target in (self.root / ".agents/skills/demo-skill", self.root / ".opencode/skills/demo-skill"):
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(source, target)
        rule = self.root / ".cursor/rules/demo-skill.mdc"
        rule.parent.mkdir(parents=True)
        rule.write_text("---\ndescription: Demo\nalwaysApply: false\n---\n\n<!-- generated by scripts/sync-skill-runtimes.sh -->\n<!-- source: .claude/skills/demo-skill/SKILL.md -->\n# Demo\n", encoding="utf-8")

    def test_missing_all_outputs_fails(self):
        result = self.run_audit()
        self.assertEqual(result.returncode, 1)
        self.assertEqual(len(json.loads(result.stdout)["findings"]), 3)

    def test_conformant_and_resource_drift(self):
        self.publish()
        self.assertEqual(self.run_audit().returncode, 0)
        extra = self.root / ".agents/skills/demo-skill/scripts/x.py"
        extra.parent.mkdir()
        extra.write_text("pass\n")
        result = self.run_audit()
        self.assertEqual(result.returncode, 1)
        self.assertIn("stale", result.stdout)

    def test_invalid_manifest_is_exit_two(self):
        self.config["published"] = ["Bad Name"]
        (self.root / ".skill-runtimes.json").write_text(json.dumps(self.config))
        self.assertEqual(self.run_audit().returncode, 2)


if __name__ == "__main__":
    unittest.main()
